// Renders the coverage report (docs/re/coverage.md) from the inventory.

import type { Inventory, InvImage } from './types.ts';

export const COVERAGE_TARGET = 99;

const hex = (n: number) => '0x' + n.toString(16).toUpperCase();
const pct = (n: number) => n.toFixed(2) + '%';

/** Sections of every image that fall short of the target. */
export function shortfalls(inv: Inventory): { image: string; section: string; percent: number }[] {
  return inv.images.flatMap((im) =>
    im.coverage.filter((c) => c.percent < COVERAGE_TARGET).map((c) => ({ image: im.name, section: c.name, percent: c.percent })),
  );
}

function totals(images: InvImage[], section: string) {
  const t = { bytes: 0, fn: 0, pad: 0, data: 0, unassigned: 0 };
  for (const im of images) {
    for (const c of im.coverage) {
      if (c.name !== section) continue;
      t.bytes += c.bytes;
      t.fn += c.functionBytes;
      t.pad += c.paddingBytes;
      t.data += c.dataBytes;
      t.unassigned += c.unassignedBytes;
    }
  }
  return t;
}

export function renderCoverage(inv: Inventory): string {
  const L: string[] = [];
  L.push('# Analysis coverage', '');
  L.push(`Generated by \`npm run analyze\` from \`out/inventory.json\` (tool: ${inv.tool.name} ${inv.tool.version}, ROM SHA-1 \`${inv.rom.sha1}\`). Do not edit by hand.`, '');
  L.push(
    'A byte counts as covered when it belongs to a function range, to zero padding, or to an identified data range (jump table, string, zero fill, object referenced by code, a relocation or a pointer in data). ' +
      `Target: at least ${COVERAGE_TARGET}% per section.`,
    '',
  );
  L.push('## Totals by section type', '');
  L.push('| Section | Bytes | Function | Padding | Data | Unassigned | Covered |', '|---|---:|---:|---:|---:|---:|---:|');
  for (const name of ['.text', '.data', '.rodata']) {
    const t = totals(inv.images, name);
    if (!t.bytes) continue;
    L.push(`| ${name} | ${t.bytes} | ${t.fn} | ${t.pad} | ${t.data} | ${t.unassigned} | ${pct((100 * (t.bytes - t.unassigned)) / t.bytes)} |`);
  }
  const bss = inv.images.flatMap((im) => im.sections.filter((s) => s.kind === 'bss'));
  L.push('', `\`.bss\` ranges recorded: ${bss.length} (${bss.reduce((n, s) => n + s.end - s.start, 0)} bytes, no file content to cover).`, '');
  const low = shortfalls(inv);
  L.push(low.length ? `**${low.length} section(s) below ${COVERAGE_TARGET}%:** ${low.map((x) => `${x.image}${x.section} ${pct(x.percent)}`).join(', ')}` : `All ${inv.images.reduce((n, im) => n + im.coverage.length, 0)} sections reach ${COVERAGE_TARGET}%.`, '');
  L.push('## Functions by confidence', '');
  const conf = { high: 0, medium: 0, low: 0 };
  let fns = 0;
  for (const im of inv.images) for (const f of im.functions) {
      conf[f.confidence]++;
      fns++;
    }
  L.push(`${fns} functions: ${conf.high} high, ${conf.medium} medium, ${conf.low} low. Low means the range was only inferred as the gap between two other functions.`, '');
  L.push('## Per image', '');
  L.push('| Image | Kind | Functions | Section | Range | Bytes | Covered |', '|---|---|---:|---|---|---:|---:|');
  for (const im of inv.images) {
    for (const c of im.coverage) {
      L.push(`| ${im.name} | ${im.kind} | ${im.functions.length} | ${c.name} | ${hex(c.start)}–${hex(c.end)} | ${c.bytes} | ${pct(c.percent)} |`);
    }
  }
  return L.join('\n') + '\n';
}
